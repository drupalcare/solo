#!/usr/bin/env python3
"""Builds Solo's region variable files from one map.

One owner: solo_utilities/config/map/solo-variable-map.yml. From it this script writes

  css/base/solo-region-properties.css   the @property registrations of the 15 region colors
  css/base/solo-region-legacy.css       one alias per removed 1.x name (old reader -> new name)
  README.md                             the upgrade table between the region-vars markers

Usage:
  build-region-legacy.py            write the three outputs (only the ones that differ)
  build-region-legacy.py --check    exit 1 when an output differs from the map (drift); writes nothing
  build-region-legacy.py --self-test  prove the check goes red: a planted drift, a duplicate old name
                                      and a new name used as an old one must each fail
"""

import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT.parent / "solo_utilities" / "config" / "map" / "solo-variable-map.yml"
PROPS = "css/base/solo-region-properties.css"
LEGACY = "css/base/solo-region-legacy.css"
README = "README.md"
START = "<!-- region-vars:start -->"
END = "<!-- region-vars:end -->"


def parse_map(text):
    """Reads the map: `roles:` with `name: {initial: value}` rows, `removed:` with 'old': 'new' rows."""
    roles, removed, section = [], {}, None
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.split(" #", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        if line in ("roles:", "removed:"):
            section = line[:-1]
            continue
        if section == "roles":
            m = re.fullmatch(r"  ([a-z-]+): \{initial: (transparent|currentcolor)\}", line)
            if not m:
                raise ValueError("map line %d: bad role row: %r" % (number, raw))
            roles.append((m.group(1), m.group(2)))
        elif section == "removed":
            m = re.fullmatch(r"  '(--[a-z0-9-]+)': '(--[a-z0-9-]+)'", line)
            if not m:
                raise ValueError("map line %d: bad removed row: %r" % (number, raw))
            if m.group(1) in removed:
                raise ValueError("map line %d: old name %s listed twice" % (number, m.group(1)))
            removed[m.group(1)] = m.group(2)
        else:
            raise ValueError("map line %d: row outside a section: %r" % (number, raw))
    new_names = {"--r-" + name for name, _ in roles}
    for old, new in removed.items():
        if old in new_names:
            raise ValueError("%s is a current name; an alias on it would be a cycle" % old)
        if old == new:
            raise ValueError("%s maps to itself" % old)
    return roles, removed


def build_properties(roles):
    out = [
        "/**",
        " * @file",
        " * Typed registrations of the %d region color variables." % len(roles),
        " *",
        " * Generated by scripts/build-region-legacy.py from",
        " * solo_utilities/config/map/solo-variable-map.yml. Do not edit.",
        " *",
        " * Each --r-<role> is a <color>: a value that is not a color (a typo, a",
        " * malformed hex, a CSS-wide keyword) is dropped when it is assigned and the",
        " * variable keeps its initial value. Backgrounds start transparent and",
        " * foregrounds start at currentcolor. --r-background-image is not a color and",
        " * is not registered: a gradient goes there, never in --r-background.",
        " *",
        " * The registrations are global, whatever layer they are written in; they sit",
        " * in solo.tokens because they are tokens. The library loads before the",
        " * stylesheet that sets the variables (solo/region-properties).",
        " */",
        "",
        "@layer solo.tokens {",
    ]
    for name, initial in roles:
        out += [
            "",
            "@property --r-%s {" % name,
            "  syntax: '<color>';",
            "  inherits: true;",
            "  initial-value: %s;" % initial,
            "}",
        ]
    out += ["", "} /* end @layer solo.tokens */", ""]
    return "\n".join(out)


def build_legacy(removed):
    out = [
        "/**",
        " * @file",
        " * Archive of the Solo 1.x region variable names.",
        " *",
        " * @deprecated in solo:2.0.0 and removed at the next major release.",
        " *",
        " * Generated by scripts/build-region-legacy.py from",
        " * solo_utilities/config/map/solo-variable-map.yml. Do not edit.",
        " *",
        " * Each old name reads the new one, so a sub-theme or stored CSS that has",
        " * `color: var(--r-tx)` keeps its color. This works one way only: a rule that",
        " * SETS an old name (`--r-tx: red`) no longer changes anything, because the",
        " * new name is not an alias of the old one (that would be a cycle and both",
        " * would become invalid). Rewrite those with `drush solo:migrate-classes`.",
        " *",
        " * Declared on the page and every element under it, so each element resolves",
        " * the new name from its own region. An old name that held a gradient",
        " * (--r-bg, --r-header-bg) now reads the color; the gradient is in",
        " * --r-background-image and --solo-accent-background-image.",
        " *",
        " * Layer: solo.tokens, the weakest layer that holds variables, so any rule a",
        " * sub-theme writes for an old name, in any layer or outside layers, wins.",
        " */",
        "",
        "@layer solo.tokens {",
        "",
        ":where(.solo-page, .solo-page *) {",
    ]
    for old in sorted(removed):
        out.append("  %s: var(%s);" % (old, removed[old]))
    out += ["}", "", "} /* end @layer solo.tokens */", ""]
    return "\n".join(out)


def build_table(removed):
    rows = ["| Old name | New name |", "| --- | --- |"]
    for old in sorted(removed):
        rows.append("| `%s` | `%s` |" % (old, removed[old]))
    return "\n".join(rows)


def readme_with(text, table):
    if START not in text or END not in text:
        raise ValueError("README.md has no %s ... %s block" % (START, END))
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + START + "\n\n" + table + "\n\n" + END + tail


def outputs(root, map_text):
    roles, removed = parse_map(map_text)
    readme = (root / README).read_text(encoding="utf-8")
    return {
        PROPS: build_properties(roles),
        LEGACY: build_legacy(removed),
        README: readme_with(readme, build_table(removed)),
    }


def drift(root, map_text):
    bad = []
    for rel, want in outputs(root, map_text).items():
        path = root / rel
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have != want:
            bad.append(rel)
    return bad


def self_test():
    failures = 0
    map_text = MAP.read_text(encoding="utf-8")
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        (root / "css/base").mkdir(parents=True)
        (root / README).write_text("a\n%s\nold\n%s\nb\n" % (START, END), encoding="utf-8")
        for rel, text in outputs(root, map_text).items():
            (root / rel).write_text(text, encoding="utf-8")
        cases = []
        cases.append(("clean tree reports no drift", drift(root, map_text) == []))
        legacy = root / LEGACY
        original = legacy.read_text(encoding="utf-8")
        legacy.write_text(original.replace("--r-tx: var(--r-text);", "--r-tx: var(--r-border);"), encoding="utf-8")
        cases.append(("planted wrong alias is drift", drift(root, map_text) == [LEGACY]))
        legacy.write_text(original, encoding="utf-8")
        legacy.write_text(original.replace("  --r-tx: var(--r-text);\n", ""), encoding="utf-8")
        cases.append(("missing alias is drift", drift(root, map_text) == [LEGACY]))
        legacy.write_text(original, encoding="utf-8")
        for label, extra in (
            ("duplicate old name is refused", "  '--r-tx': '--r-text'\n"),
            ("a current name as old name is refused", "  '--r-text': '--r-heading'\n"),
        ):
            try:
                parse_map(map_text + extra)
                cases.append((label, False))
            except ValueError:
                cases.append((label, True))
        count = len(re.findall(r"^  --r-[a-z0-9-]+: var\(", original, re.M))
        cases.append(("one archive line per old name", count == len(parse_map(map_text)[1])))
    for label, ok in cases:
        print(("PASS " if ok else "FAIL ") + label)
        failures += 0 if ok else 1
    print("self-test failures: %d" % failures)
    return 1 if failures else 0


def main(argv):
    if "--self-test" in argv:
        return self_test()
    map_text = MAP.read_text(encoding="utf-8")
    if "--check" in argv:
        bad = drift(ROOT, map_text)
        for rel in bad:
            print("DRIFT: %s differs from solo-variable-map.yml" % rel)
        print("region variable files: %s" % ("DRIFT" if bad else "OK"))
        return 1 if bad else 0
    for rel, want in outputs(ROOT, map_text).items():
        path = ROOT / rel
        if not path.exists() or path.read_text(encoding="utf-8") != want:
            path.write_text(want, encoding="utf-8")
            print("wrote %s" % rel)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
